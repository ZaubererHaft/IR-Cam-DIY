static int32_t lower_scaled = 200;
static uint32_t span_scaled = 200u;
static const uint16_t *active_lut = heatmap_lut[0];


const char *Heatmap_GetNameByIndex(uint32_t index) {
    return heatmap_names[index];
}

uint32_t Heatmap_GetSize() {
    return 7;
}

RGB565_t Heatmap_TempScaledToRGB565(int16_t scaled_temp) {
    const int32_t delta = (int32_t) scaled_temp - lower_scaled;
    RGB565_t ret;

    if (delta <= 0) {
        ret.raw = active_lut[0];
    } else if ((uint32_t) delta >= span_scaled) {
        ret.raw = active_lut[255];
    } else {
        /* Round the normalized index to nearest; midpoint rounds upward.
         * Largest possible numerator is less than 2^24, so uint32_t suffices.
         * span_scaled is always >= 1, including before the first setter call.
         */
        uint32_t index = ((uint32_t) delta * 255u + span_scaled / 2u) / span_scaled;
        ret.raw = active_lut[index];
    }

    return ret;
}

RGB565_t Heatmap_TempToRGB565(float temp_celsius) {
    return Heatmap_TempScaledToRGB565((int16_t) temp_celsius * TEMPERATURE_SCALING);
}


void Heatmap_ConfigObserver(Config config) {
    lower_scaled = Temperature_FromFloat(config.tMin);
    span_scaled = Temperature_FromFloat(config.tMax) - Temperature_FromFloat(config.tMin);
    active_lut = heatmap_lut[config.heatmap_index];
}


int16_t Temperature_FromFloat(float temp_cel) {
    return (int16_t) (temp_cel * TEMPERATURE_SCALING);
}

float Temperature_ToFloat(int16_t temp_cel) {
    return (float) temp_cel / (float) TEMPERATURE_SCALING;
}
